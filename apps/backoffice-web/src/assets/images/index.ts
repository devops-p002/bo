// Utility functions for image handling
export const getImageUrl = (imagePath) => {
  // Handle both imported images and public folder images
  if (typeof imagePath === 'string' && imagePath.startsWith('/')) {
    return imagePath;
  }
  return imagePath;
};

export const getVipIcon = (level) => {
  return icons.vipLevels[level] || icons.vipLevels.bronze;
};

export const getRiskIcon = (level) => {
  return icons.riskLevels[level] || icons.riskLevels.low;
};

export const getStatusIcon = (status) => {
  return icons.status[status] || icons.status.inactive;
};

export const getPaymentIcon = (method) => {
  return icons.paymentMethods[method] || icons.paymentMethods.creditCard;
};

export const getGameCategoryIcon = (category) => {
  return icons.gameCategories[category] || icons.gameCategories.slots;
};

export const getProviderLogo = (provider) => {
  return providers[provider] || providers.evolution;
};

export const getCountryFlag = (countryCode) => {
  return flags[countryCode.toLowerCase()] || flags.us;
};

